#include <stdio.h>

static void swap(int *p, int *q)
{
    int t = *p;
    *p = *q;
    *q = t;
}

void sort3(int *a, int *b, int *c)
{
    if (*a > *b) swap(a, b);
    if (*b > *c) swap(b, c);
    if (*a > *b) swap(a, b);
}

int main(void)
{
    int x = 7, y = 2, z = 5;

    printf("До:    x = %d, y = %d, z = %d\n", x, y, z);
    sort3(&x, &y, &z);
    printf("После: x = %d, y = %d, z = %d\n", x, y, z);

    /*
     * Передача по значению: функция получает копию, и изменения внутри
     * функции исходную переменную не затрагивают. Передача по указателю:
     * функция получает адрес переменной (оператор &), а оператор
     * разыменования * позволяет читать и менять значение по этому адресу,
     * поэтому изменения видны в вызывающей функции (в main).
     */
    return 0;
}
