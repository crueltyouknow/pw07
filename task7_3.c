#include <stdio.h>

double cube_of_sum(double a, double b)
{
    double s = a + b;
    return s * s * s;
}

int main(void)
{
    double a, b;

    printf("Введите пары чисел a b (для выхода введите не число):\n");
    while (scanf("%lf %lf", &a, &b) == 2) {
        printf("Результат: %.4f\n", cube_of_sum(a, b));
    }
    /*
     * Условие scanf(...) == 2 защищает от некорректного ввода: scanf
     * возвращает число успешно прочитанных значений, и как только введено
     * не число (или кончился ввод), цикл завершается. Аргументы передаются
     * в функцию по значению: она работает с копиями a и b.
     */
    return 0;
}
